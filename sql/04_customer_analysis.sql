-- -----------------------------------------------------------------------------
-- QUERY 9: TOTAL UNIQUE CUSTOMERS VS TOTAL TRANSACTION ORDERS
-- -----------------------------------------------------------------------------
-- Business Purpose:
--   Clarify the critical distinction between transactional `customer_id` (one generated
--   per checkout) and `customer_unique_id` (the actual individual person placing orders).
--
-- SQL Logic:
--   Aggregates total customer rows, distinct customer_unique_ids, and total placed orders.
--
-- Business Implication:
--   Demonstrates that nearly 97% of customer_unique_ids in Olist correspond to a single
--   purchase, establishing that Olist behaves primarily as an acquisition funnel rather
--   than a high-retention subscription platform.

SELECT 
    COUNT(c.customer_id) AS total_customer_checkout_records,
    COUNT(DISTINCT c.customer_unique_id) AS total_unique_individual_customers,
    COUNT(DISTINCT o.order_id) AS total_orders_placed,
    ROUND(
        COUNT(DISTINCT o.order_id)::NUMERIC / COUNT(DISTINCT c.customer_unique_id), 
        3
    ) AS avg_orders_per_unique_customer
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id;


-- -----------------------------------------------------------------------------
-- QUERY 10: REPEAT CUSTOMER PERCENTAGE AND REVENUE CONTRIBUTION
-- -----------------------------------------------------------------------------
-- Business Purpose:
--   Quantify the repeat customer rate and compare total revenue generated by
--   one-time buyers vs repeat multi-order purchasers.
--
-- SQL Logic:
--   Uses a CTE to group delivered orders by customer_unique_id. Categorizes customers
--   into 'One-Time Buyer' (1 order) vs 'Repeat Buyer' (>1 order), then aggregates counts
--   and cumulative revenue.
--
-- Business Implication:
--   Repeat customers represent approximately 3.0% of the customer base, yet generate
--   over 6.5% of total merchandise revenue. Increasing repeat purchase rates even by 2%
--   would deliver outsized margin gains due to zero incremental acquisition cost.

WITH customer_order_summary AS (
    SELECT 
        c.customer_unique_id,
        COUNT(DISTINCT o.order_id) AS lifetime_orders,
        SUM(oi.price) AS total_spend
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id
)
SELECT 
    CASE 
        WHEN lifetime_orders = 1 THEN 'One-Time Buyer (1 Order)'
        WHEN lifetime_orders BETWEEN 2 AND 3 THEN 'Repeat Buyer (2-3 Orders)'
        ELSE 'Frequent Buyer (4+ Orders)'
    END AS customer_loyalty_tier,
    COUNT(customer_unique_id) AS customer_count,
    ROUND(
        COUNT(customer_unique_id)::NUMERIC / SUM(COUNT(customer_unique_id)) OVER () * 100, 
        2
    ) AS pct_of_customers,
    ROUND(SUM(total_spend), 2) AS total_spend_volume,
    ROUND(
        SUM(total_spend) / SUM(SUM(total_spend)) OVER () * 100, 
        2
    ) AS revenue_contribution_pct,
    ROUND(AVG(total_spend), 2) AS avg_spend_per_customer
FROM customer_order_summary
GROUP BY 
    CASE 
        WHEN lifetime_orders = 1 THEN 'One-Time Buyer (1 Order)'
        WHEN lifetime_orders BETWEEN 2 AND 3 THEN 'Repeat Buyer (2-3 Orders)'
        ELSE 'Frequent Buyer (4+ Orders)'
    END
ORDER BY total_spend_volume DESC;


-- -----------------------------------------------------------------------------
-- QUERY 11: TOP 20 INDIVIDUAL CUSTOMERS BY LIFETIME SPEND
-- -----------------------------------------------------------------------------
-- Business Purpose:
--   Identify VIP whales and high-net-worth accounts for loyalty programs and personalized outreach.
--
-- SQL Logic:
--   Groups delivered orders by customer_unique_id, aggregating total spend, total orders,
--   total items bought, and identifying primary state. Ranks using DENSE_RANK().
--
-- Business Implication:
--   Top individual accounts spent up to R$ 13,000+ across commercial supplies or luxury goods,
--   representing B2B micro-enterprise buying patterns rather than standard consumer purchases.

SELECT 
    c.customer_unique_id,
    MAX(c.customer_state) AS primary_state,
    COUNT(DISTINCT o.order_id) AS total_delivered_orders,
    COUNT(oi.order_item_id) AS total_items_purchased,
    ROUND(SUM(oi.price), 2) AS total_product_spend,
    ROUND(SUM(oi.freight_value), 2) AS total_freight_paid,
    ROUND(SUM(oi.price + oi.freight_value), 2) AS gross_spend_with_shipping
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
JOIN order_items oi ON o.order_id = oi.order_id
WHERE o.order_status = 'delivered'
GROUP BY c.customer_unique_id
ORDER BY total_product_spend DESC
LIMIT 20;


-- -----------------------------------------------------------------------------
-- QUERY 12: CUSTOMER PURCHASE FREQUENCY HISTOGRAM DISTRIBUTION
-- -----------------------------------------------------------------------------
-- Business Purpose:
--   Provide a complete granular frequency distribution of order counts across the customer base.
--
-- SQL Logic:
--   Calculates orders per customer_unique_id in an inner CTE, then aggregates distribution counts.
--
-- Business Implication:
--   Confirms intense drop-off after the first purchase, indicating high opportunity for
--   post-purchase lifecycle email triggers, replenishment reminders, and coupon retargeting.

WITH customer_freq AS (
    SELECT 
        c.customer_unique_id,
        COUNT(DISTINCT o.order_id) AS order_count
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id
)
SELECT 
    order_count AS orders_placed_by_customer,
    COUNT(*) AS total_customers,
    ROUND(COUNT(*)::NUMERIC / SUM(COUNT(*)) OVER () * 100, 3) AS customer_share_pct
FROM customer_freq
GROUP BY order_count
ORDER BY orders_placed_by_customer;


-- -----------------------------------------------------------------------------
-- QUERY 13: MONTHLY EVOLUTION OF NEW VS RETURNING CUSTOMERS
-- -----------------------------------------------------------------------------
-- Business Purpose:
--   Evaluate whether monthly order volume is composed of brand-new first-time buyers
--   or re-engaged returning shoppers over time.
--
-- SQL Logic:
--   Determines each customer_unique_id's first purchase date using MIN() window function.
--   Flags each order as 'New Customer' if purchase_timestamp equals first_order_timestamp,
--   else 'Returning Customer'.
--
-- Business Implication:
--   Reveals that month after month, over 95% of active monthly shoppers were first-time
--   visitors, proving that marketing was overwhelmingly top-of-funnel acquisition heavy.

WITH customer_first_orders AS (
    SELECT 
        c.customer_unique_id,
        o.order_id,
        o.order_purchase_timestamp,
        MIN(o.order_purchase_timestamp) OVER(PARTITION BY c.customer_unique_id) AS first_purchase_date
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    WHERE o.order_status = 'delivered'
)
SELECT 
    TO_CHAR(order_purchase_timestamp, 'YYYY-MM') AS year_month,
    COUNT(DISTINCT order_id) AS total_orders,
    COUNT(DISTINCT CASE WHEN order_purchase_timestamp = first_purchase_date THEN order_id END) AS new_customer_orders,
    COUNT(DISTINCT CASE WHEN order_purchase_timestamp > first_purchase_date THEN order_id END) AS returning_customer_orders,
    ROUND(
        COUNT(DISTINCT CASE WHEN order_purchase_timestamp > first_purchase_date THEN order_id END)::NUMERIC / 
        COUNT(DISTINCT order_id) * 100, 
        2
    ) AS returning_customer_order_share_pct
FROM customer_first_orders
GROUP BY TO_CHAR(order_purchase_timestamp, 'YYYY-MM')
ORDER BY year_month;


-- -----------------------------------------------------------------------------
-- QUERY 14: CUSTOMER RFM SEGMENTATION MODEL (RECENCY, FREQUENCY, MONETARY)
-- -----------------------------------------------------------------------------
-- Business Purpose:
--   Segment customer accounts into actionable behavioral cohorts (Champions, Loyal,
--   Promising, At Risk, Lost) using Recency, Frequency, and Monetary scoring in pure SQL.
--
-- SQL Logic:
--   1. Computes raw Recency (days since last order), Frequency (distinct orders),
--      and Monetary (total product revenue).
--   2. Uses NTILE(5) window functions to divide recency, frequency, and monetary into quintiles.
--   3. Maps combined scores into meaningful strategic business personas.
--
-- Business Implication:
--   Enables marketing teams to direct retention budgets away from low-value dormant accounts
--   towards high-value 'Champions' and high-monetary 'At Risk' accounts.

WITH rfm_raw AS (
    SELECT 
        c.customer_unique_id,
        -- Reference date set to dataset max date + 1 day
        ('2018-09-04 00:00:00'::TIMESTAMP - MAX(o.order_purchase_timestamp))::TEXT AS recency_interval,
        EXTRACT(DAY FROM ('2018-09-04 00:00:00'::TIMESTAMP - MAX(o.order_purchase_timestamp))) AS recency_days,
        COUNT(DISTINCT o.order_id) AS frequency,
        ROUND(SUM(oi.price), 2) AS monetary
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id
),
rfm_scores AS (
    SELECT 
        customer_unique_id,
        recency_days,
        frequency,
        monetary,
        NTILE(5) OVER (ORDER BY recency_days DESC) AS r_score, -- Lower recency days gets higher score
        NTILE(5) OVER (ORDER BY frequency ASC) AS f_score,
        NTILE(5) OVER (ORDER BY monetary ASC) AS m_score
    FROM rfm_raw
)
SELECT 
    CASE 
        WHEN r_score >= 4 AND f_score >= 4 THEN 'Champions'
        WHEN r_score >= 3 AND f_score >= 3 THEN 'Loyal Customers'
        WHEN r_score >= 4 AND f_score <= 2 THEN 'Recent Promising'
        WHEN r_score = 3 AND f_score <= 2 THEN 'Needs Attention'
        WHEN r_score <= 2 AND f_score >= 3 THEN 'At Risk'
        WHEN r_score <= 2 AND f_score <= 2 AND m_score >= 4 THEN 'High-Value Churned'
        ELSE 'Lost / Dormant'
    END AS rfm_segment,
    COUNT(*) AS total_customers,
    ROUND(AVG(recency_days), 1) AS avg_recency_days,
    ROUND(AVG(frequency), 2) AS avg_frequency,
    ROUND(AVG(monetary), 2) AS avg_monetary_spend,
    ROUND(SUM(monetary), 2) AS total_segment_revenue,
    ROUND(
        SUM(monetary) / SUM(SUM(monetary)) OVER () * 100, 
        2
    ) AS revenue_share_pct
FROM rfm_scores
GROUP BY 
    CASE 
        WHEN r_score >= 4 AND f_score >= 4 THEN 'Champions'
        WHEN r_score >= 3 AND f_score >= 3 THEN 'Loyal Customers'
        WHEN r_score >= 4 AND f_score <= 2 THEN 'Recent Promising'
        WHEN r_score = 3 AND f_score <= 2 THEN 'Needs Attention'
        WHEN r_score <= 2 AND f_score >= 3 THEN 'At Risk'
        WHEN r_score <= 2 AND f_score <= 2 AND m_score >= 4 THEN 'High-Value Churned'
        ELSE 'Lost / Dormant'
    END
ORDER BY total_segment_revenue DESC;
